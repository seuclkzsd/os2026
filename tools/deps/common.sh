# Shared helpers of tools/deps/build_*.sh (sourced, not executed). docs/BLAS.md describes the builds.
#
# Layout (all under $HS_DEPS, default $HOME/deps):
#   src/<tarball>            pinned source tarballs. The cluster nodes have no internet: download on
#                            a machine that has (URLs in each build script), check the sha256 there,
#                            rsync into src/; every build checks the sha256 again before unpacking.
#   build/<lib>-<ver>-<name> fresh build tree per build (removed first when it exists)
#   <lib>-<ver>-<name>/      install prefix; BUILD-INFO.txt records tarball, checksum, flags, compiler
# The build tools come from the project environment: run the scripts through env/run.sh (or after
# `source env/activate.sh`) so that CC / FC / CXX are conda-forge's GCC 13 and libgomp is the
# environment's (the one MUMPS and hsolve use). HS_JOBS (default 4) sets the build parallelism.
set -euo pipefail

HS_DEPS="${HS_DEPS:-$HOME/deps}"
HS_DEPS_SRC="${HS_DEPS_SRC:-$HS_DEPS/src}"
HS_DEPS_BUILD="${HS_DEPS_BUILD:-$HS_DEPS/build}"

deps_die() {
  echo "deps: $*" >&2
  exit 1
}

# deps_check FILE SHA256: the tarball exists and has the pinned checksum.
deps_check() {
  local file="$1" want="$2" got
  [ -f "$file" ] || deps_die "missing source tarball $file (download it, check sha256 $want, copy it there)"
  got="$(sha256sum "$file" | cut -d' ' -f1)"
  [ "$got" = "$want" ] || deps_die "sha256 mismatch for $file: got $got, want $want"
}

# deps_unpack TARBALL DIR: DIR is created fresh and receives the tarball's single top directory.
deps_unpack() {
  local tarball="$1" dir="$2"
  rm -rf "$dir"
  mkdir -p "$dir"
  tar -xzf "$tarball" -C "$dir" --strip-components=1 --no-same-owner
}

# deps_info PREFIX TARBALL SHA256 FLAGS...: provenance file of an install.
deps_info() {
  local prefix="$1" tarball="$2" sha="$3"
  shift 3
  {
    echo "tarball: $(basename "$tarball")"
    echo "sha256: $sha"
    echo "flags: $*"
    echo "cc: $(${CC:-cc} --version | head -1)"
    echo "host: $(hostname -s) $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2)"
    echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  } > "$prefix/BUILD-INFO.txt"
}

deps_jobs() {
  echo "${HS_JOBS:-4}"
}

# deps_glibc_compat DIR: prints linker flags that keep a library runnable on glibc 2.17.
# The project environment's compilers use a glibc 2.28 sysroot (sysroot_linux-64 2.28), the
# cluster nodes (and possibly the judging machine) run glibc 2.17; libm's expf / logf / powf /
# exp2f got new symbol versions in 2.27 (exp / log / pow in 2.29), so a library built here would
# not load there ("version GLIBC_2.27 not found"; OpenBLAS' LAPACK and LIBXSMM call them).
# The flags wrap those calls (-Wl,--wrap) into a generated object whose hidden __wrap_* functions
# call the GLIBC_2.2.5 versions - the same libm code paths the old symbols always had.
deps_glibc_compat() {
  local dir="$1" src="$1/hs_glibc_compat.c" obj="$1/hs_glibc_compat.o" f wraps=""
  {
    echo "/* Generated by tools/deps/common.sh (deps_glibc_compat). */"
    for f in expf logf exp2f; do
      echo "__asm__(\".symver hs_old_$f,$f@GLIBC_2.2.5\");"
      echo "float hs_old_$f(float);"
      echo "__attribute__((visibility(\"hidden\"))) float __wrap_$f(float x) { return hs_old_$f(x); }"
    done
    echo "__asm__(\".symver hs_old_powf,powf@GLIBC_2.2.5\");"
    echo "float hs_old_powf(float, float);"
    echo "__attribute__((visibility(\"hidden\"))) float __wrap_powf(float x, float y) { return hs_old_powf(x, y); }"
    for f in exp log; do
      echo "__asm__(\".symver hs_old_$f,$f@GLIBC_2.2.5\");"
      echo "double hs_old_$f(double);"
      echo "__attribute__((visibility(\"hidden\"))) double __wrap_$f(double x) { return hs_old_$f(x); }"
    done
    echo "__asm__(\".symver hs_old_pow,pow@GLIBC_2.2.5\");"
    echo "double hs_old_pow(double, double);"
    echo "__attribute__((visibility(\"hidden\"))) double __wrap_pow(double x, double y) { return hs_old_pow(x, y); }"
  } > "$src"
  "${CC:-cc}" -O2 -fPIC -fno-builtin -c "$src" -o "$obj"
  for f in expf logf exp2f powf exp log pow; do wraps+=",--wrap=$f"; done
  echo "-Wl${wraps} $obj"
}

# deps_check_glibc LIB: fails when LIB needs a glibc symbol version newer than 2.17.
deps_check_glibc() {
  local bad
  bad="$("${OBJDUMP:-objdump}" -T "$1" | grep -E 'GLIBC_2\.(1[89]|[2-9][0-9])' || true)"
  [ -z "$bad" ] || deps_die "$1 needs glibc > 2.17: $bad"
}

deps_require_env() {
  [ -n "${CONDA_PREFIX:-}" ] && [ -n "${CC:-}" ] ||
    deps_die "run through env/run.sh (conda-forge compilers and libgomp of the project environment)"
}
